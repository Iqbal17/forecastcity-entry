"""Charm the Commuter: Forecast a City That Isn't — make.fun entry.

Decision record (24 Nov 2026, writer session):

The gate is one line of weather, 1-140 characters, for a city that does not
exist. The judge is a bored commuter reading the forecast on a phone at a
rainy bus stop, weighing in order: (1) reads as a one-line forecast for a
named invented city, weather the whole point; (2) makes the commuter smile
on one reading; (3) keeps the register of a real broadcast forecast, bent
rather than dropped; (4) one concrete detail of the city's weather or life;
(5) every word earning its place. Quirkiness for its own sake does not count.

Candidates weighed:

A. Zorbia (CHOSEN): "Zorbia: scattered sunshine and one very personal
   thunderstorm following you to work. Umbrella optional, dignity unlikely."
   (121 chars) The weather is the whole point — a thunderstorm, only a
   personal one, so criterion 1 holds while the joke lands. "Scattered
   sunshine" and "Umbrella optional" keep the broadcast register; the storm
   following you to work is the commuter's-eye detail; "dignity unlikely"
   is the punch, in the last two words. Every clause does work.

B. Drizzleford: "Drizzleford: overnight rain, morning fog, then a 9 a.m.
   hail of unread emails. Buses on time, spirits delayed." (110 chars)
   The strongest broadcast rhythm of the four — "overnight rain, morning
   fog" reads straight off the radio — and "spirits delayed" is a sweet
   punch. It loses because the weather stops being weather halfway through:
   a hail of emails is an office joke wearing a forecast's coat, so it
   falls at criterion 1, the first and most important.

C. Wobbleton: "Wobbleton: heavy rain, and a strong chance your umbrella
   will betray you before the 8:15 bus. Pack patience." (114 chars)
   A real commuter grievance and a clear punch ("betray you"), but the
   joke is familiar — umbrellas failing is the first joke every forecast
   reaches for — so it loses on surprise at criterion 2, and "Pack
   patience" is advice, not a turn of phrase.

D. Mizzlewick: "Mizzlewick: 100% chance of rain, 0% chance the bus
   shelter fits everyone. Queue early, get wet together." (104 chars)
   The bus-shelter detail is the most commuter-true image of the four,
   but the ending is warm rather than funny; it smiles politely where
   Zorbia's "dignity unlikely" actually makes the commuter laugh, and it
   spends its last words on logistics instead of a punch.

Writing passes on the chosen line:

Pass 1: "Zorbia: scattered sunshine, with one thunderstorm following you
to work. Umbrella optional, dignity unlikely." The skeleton was right —
forecast opening, storm, commuter, punch — but "one thunderstorm" was
flat: any city can have a thunderstorm, and nothing made it Zorbia's.

Pass 2: replaced "with one thunderstorm" with "and one very personal
thunderstorm". "Very personal" makes the storm single the commuter out,
which is the whole joke: the weather is not bad in general, it is out to
get you specifically. The comma splice went with it, so the line now
reads in one broadcast breath: forecast, storm, commute, punch.

REVISION PASS (24 Nov 2026) — a second, longer session. I re-read the
chosen line against the judge's brief word by word, because the first
session was short and the kit check asked for real revision work, not a
rubber stamp. The line under review:

    Zorbia: scattered sunshine and one very personal thunderstorm
    following you to work. Umbrella optional, dignity unlikely.
    (121 characters)

Criterion-by-criterion critique:

1. Reads as a one-line forecast for a named invented city, weather the
whole point. This is the line's strongest suit, and it is the criterion
the judge weighs first, so it matters most. Zorbia is named in the first
word, before the colon, exactly where a broadcast forecast puts the
place. The weather — sunshine, then a thunderstorm — is the subject of
every clause, and the joke is not a costume draped over the weather, it
IS the weather behaving wrongly. The line never drifts into office life
or commentary about anything but the sky. Nothing here needs fixing.

2. Makes a bored commuter smile on one reading. The smile comes in two
beats: "very personal thunderstorm" — a storm with intent, singling you
out — and "dignity unlikely" — the cost of the storm named as a forecast
value, the way a bulletin says "rain likely". Both are surprises, and
both land on one reading: the first reframes weather as personal, the
second treats dignity as a meteorological quantity. The risk is that
"very personal" does most of the work and the rest is setup, but the
setup is short, so the ratio is fine. A commuter at a rainy bus stop
reads this and recognises the feeling immediately: the rain is not
falling on everyone, it is falling on them.

3. Keeps the register of a real forecast, the rhythm of broadcast
weather bent rather than dropped. "Scattered sunshine" and "Umbrella
optional" are real forecast phrases, and the line's cadence — place,
conditions, advice — follows a broadcast bulletin. "Dignity unlikely"
bends the register in exactly the way the brief asks: it borrows the
forecast's probability language ("unlikely") and applies it to the wrong
noun. The register holds throughout; nothing in the line drops out of
forecast voice into plain commentary.

4. Gives the invented city one concrete detail of its weather or its
life, so it feels like a place. "Following you to work" is the detail:
not just a storm, a storm with a commute. It puts the reader in the
scene — walking to work, being followed — and it makes Zorbia feel like
a place with a rush hour rather than a name on a map. Strong.

5. Uses its 140 characters well, with every word earning its place.
This is where the line is weakest, and the weakness has a name:
"scattered sunshine". It is the only phrase in the line that any
forecast for any city could say. It earns its place only as contrast —
sunshine everywhere, storm on you — but it spends 22 characters
("scattered sunshine and") on contrast that a single word, "except",
delivers in 7. The line is 121 characters with 19 unspent; the unspent
budget is not itself a fault (criterion 5 is about every word earning
its place, not about filling the budget), but the filler phrase is. Two
words I weighed and kept: "one" in "one very personal thunderstorm"
earns its place, because it isolates a single storm in an otherwise
sunny city, which is the absurdity; and "very" earns its place too,
because without it the storm is merely personal, while with it the storm
has intent. The tightening target is "scattered sunshine and", and only
that.

Fresh alternatives — five new cities, each with a different absurd
weather condition, written from scratch in this session and weighed
against Zorbia:

A. Lumenfall (124 chars): "Lumenfall: light rain all day, heavy rain
exactly while you wait for the bus, clear skies the moment you arrive
soaking wet." The strongest challenger. The register is pure forecast
from start to finish — no commentary words at all — and the cruelty is
timed to the commute, which is commuter-true: the rain is worst exactly
while you wait and stops the moment you are already wet. But it is a
small story in three beats rather than a single image, and the punch
("arrive soaking wet") states the outcome instead of twisting it, where
"dignity unlikely" twists. "Clear skies the moment you arrive" is also
a familiar ironic-weather trope. Close, but Zorbia's single image and
sharper punch win.

B. Gustwick (101 chars): "Gustwick: strong gusts from the west, strong
enough to return your umbrella to the shop it came from." The
umbrella-return image is the most surprising single image of the five —
an umbrella blown backwards through the shop door is genuinely absurd
and visual. But the setup is thin: "strong gusts from the west" is plain
forecast filler, the city gets no detail of its life beyond the
umbrella, and "strong enough to return" telegraphs the punch a beat
early. Umbrellas failing is also the first joke every forecast reaches
for. Loses on surprise at criterion 2.

C. Drizzleport (101 chars): "Drizzleport: a 90% chance of rain, a
100% chance the office air conditioning is colder than the rain." Fails
criterion 1, the first and most important: the weather stops being
weather halfway through. The second half is an office joke about air
conditioning wearing a forecast's coat — the same flaw that sank the
original candidate B. The punch is real (every office worker knows that
cold), but the judge weighs criterion 1 first, so it loses.

D. Snozzle (85 chars): "Snozzle: snow flurries, one flurry per
commuter, each one aimed directly at the eyes." Charming and economical,
and it uses the same mechanism as Zorbia — weather that singles you
out. But it is the same joke with a weaker vehicle: a flurry aimed at
the eyes is a smaller indignity than a whole thunderstorm following
you, and "aimed directly at the eyes" names the mechanism where
"dignity unlikely" names the cost. It also leaves 55 of the 140
characters unspent, which criterion 5 notices. Loses as a near-duplicate
with less force.

E. Blazeton (73 chars): "Blazeton: 38 degrees by 8 a.m., and the
shade has already called in sick." "The shade has already called in
sick" is a lovely turn — personified shade, office language applied to
weather. But the line is only 73 characters, half the budget unspent,
and the first half ("38 degrees by 8 a.m.") is straight weather with no
invention; the city could be anywhere hot. It also misses the judge
persona: the judge is a bored commuter standing at a rainy bus stop, so
a rain joke meets them where they are and a heat joke does not.

Decision: KEEP Zorbia. After five fresh alternatives, it still wins:
the single surprising image, weather the whole point throughout, the
broadcast register kept, the commuter detail, and the sharpest punch.
But the critique of criterion 5 stands, so the line is tightened, not
kept verbatim.

Tightening pass — before / after:

BEFORE (121 chars):
    Zorbia: scattered sunshine and one very personal thunderstorm
    following you to work. Umbrella optional, dignity unlikely.

AFTER (112 chars):
    Zorbia: sunny, except one very personal thunderstorm following
    you to work. Umbrella optional, dignity unlikely.

The change: "scattered sunshine and" (22 characters) becomes "sunny,
except" (13 characters). Three reasons. First, "sunny, except" keeps
the broadcast register — real forecasts say "sunny, except for..." — and
makes the storm a correction to the forecast itself, which is funnier
than a list of two conditions. Second, it removes the only generic
phrase in the line; every remaining word is either forecast voice or the
joke. Third, it sharpens the rhythm: the line now reads in one breath
with the exception landing early, so the storm arrives as a surprise
instead of as the second item in a list. What did NOT change, and why:
"one very personal thunderstorm" is untouched — "one" isolates the
storm, "very" gives it intent; "following you to work" is untouched —
it is the commuter detail; "Umbrella optional, dignity unlikely" is
untouched — it is the punch, and it now lands harder because the line
is nine characters shorter and gets there faster.

Final line (112 characters, one line, inside the 1-140 gate):

    Zorbia: sunny, except one very personal thunderstorm following
    you to work. Umbrella optional, dignity unlikely.
"""

import os

LINE = (
    "Zorbia: sunny, except one very personal thunderstorm "
    "following you to work. Umbrella optional, dignity unlikely."
)


def main() -> None:
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    path = os.path.join(out_dir, "entry.txt")
    os.makedirs(out_dir, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(LINE + "\n")
    print(LINE)
    # Read-back verification: the file must hold exactly the intended line.
    with open(path, "r", encoding="utf-8") as f:
        written = f.read().rstrip("\n")
    assert written == LINE, f"entry.txt mismatch: {written!r} != {LINE!r}"
    assert 1 <= len(written) <= 140, f"gate failed: {len(written)} chars"
    print(f"chars: {len(written)}")


if __name__ == "__main__":
    main()
